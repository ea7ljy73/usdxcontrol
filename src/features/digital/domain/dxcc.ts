const PREFIX_MAP = new Map<string, DxccEntity>()
for (const e of DXCC) {
  for (const p of e.prefixes) {
    PREFIX_MAP.set(p, e)
  }
}

export const DXCC_TOTAL = DXCC.length

export function resolveDxcc(call: string): { entity: string; cont: string } | null {
  const base = call.toUpperCase().split('/')[0]
  const m = base.match(/^(\d?[A-Z]{1,2}\d?)/)
  let prefix = m ? m[1] : base.slice(0, 2)
  while (prefix.length >= 1) {
    const e = PREFIX_MAP.get(prefix)
    if (e) return { entity: e.entity, cont: e.cont }
    prefix = prefix.slice(0, -1)
  }
  return null
}

export function isSpanishCall(call: string): boolean {
  return /^(EA|EB|EC|ED|EE|EF|EG|EH|EI|EJ)/i.test(call.toUpperCase().split('/')[0])
}

