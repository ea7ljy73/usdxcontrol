import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

const MOCK_URL = '/?radio=mock'

test('conexión a la radio simulada y control completo', async ({ page }) => {
  // Recorre toda la pantalla, con esperas reales (scan, desmarcado del dial): necesita más de 30 s.
  test.setTimeout(60_000)
  const errors: string[] = []
  page.on('console', (msg) => {
    if (msg.type() === 'error') errors.push(msg.text())
  })
  page.on('pageerror', (err) => errors.push(err.message))

  await page.goto(MOCK_URL)
  await page.getByRole('button', { name: 'Conectar radio' }).click()
  await expect(page.getByTestId('connection-status')).toHaveText('Conectado', { timeout: 5_000 })

  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.074.000')
  const usb = page.getByRole('radio', { name: 'USB' })
  await expect(usb).toBeEnabled()
  await expect(usb).toHaveAttribute('aria-checked', 'true')

  await page.getByRole('radio', { name: 'CW' }).click()
  await expect(page.getByRole('radio', { name: 'CW' })).toHaveAttribute('aria-checked', 'true')

  await page.getByRole('button', { name: 'Editar frecuencia' }).click()
  const input = page.getByLabel('Frecuencia en hercios')
  await expect(input).toBeVisible()
  await input.fill('7100000')
  await input.press('Enter')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.100.000')

  await page.getByRole('button', { name: 'Paso de sintonía 1k, clic para cambiar' }).click()
  await expect(page.getByTestId('tuning-step')).toHaveText('10k')
  await page.getByRole('button', { name: 'Subir frecuencia' }).click()
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.110.000')

  await page.getByRole('button', { name: /VFO B 7\.074\.000/ }).click()
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.074.000')
  await page.getByRole('button', { name: 'Intercambiar VFO A y B' }).click()
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.110.000')

  await page.getByTestId('band-20m').click()
  await expect(page.getByTestId('vfo-frequency')).toHaveText('14.074.000')
  await expect(page.getByTestId('band-20m')).toHaveAttribute('aria-pressed', 'true')
  await page.getByTestId('band-40m').click()
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.074.000')

  const ptt = page.getByTestId('ptt')
  await ptt.scrollIntoViewIfNeeded()
  const pttCaja = await ptt.boundingBox()
  expect(pttCaja).not.toBeNull()
  await page.mouse.move(pttCaja!.x + pttCaja!.width / 2, pttCaja!.y + pttCaja!.height / 2)
  await page.mouse.down()
  await expect(ptt).toHaveText('TX')
  await expect(ptt).toHaveAttribute('aria-pressed', 'true')
  await page.mouse.up()
  await expect(ptt).toHaveText('PTT')
  await expect(ptt).toHaveAttribute('aria-pressed', 'false')

  await page.getByRole('heading', { name: 'uSDX Control' }).click()
  await page.keyboard.press('[')
  await expect(page.getByTestId('tuning-step')).toHaveText('1k')
  await page.keyboard.press('ArrowUp')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.075.000')
  await page.keyboard.press('m')
  await expect(page.getByRole('radio', { name: 'FM' })).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.down(' ')
  await expect(ptt).toHaveText('TX')
  await page.keyboard.up(' ')
  await expect(ptt).toHaveText('PTT')

  const zoom = page.getByTestId('spectrum-zoom')
  await expect(zoom).toHaveText('BAND')
  const sliceLine = page.getByTestId('slice-line')
  const posicionLinea = () => sliceLine.evaluate((element) => Number.parseFloat((element as HTMLElement).style.left))
  const enBanda = await posicionLinea()
  await page.getByRole('heading', { name: 'uSDX Control' }).click()
  await page.keyboard.press(']')
  await page.keyboard.press(']')
  // Con paso de 100k, desde 7.075.000 el primer paso cae en la rejilla (7.100.000).
  await page.keyboard.press('ArrowUp')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.100.000')
  await page.keyboard.press('ArrowUp')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.200.000')
  await expect.poll(posicionLinea).toBeGreaterThan(enBanda + 20)
  await page.keyboard.press('[')
  await page.keyboard.press('[')
  await expect(page.getByTestId('tuning-step')).toHaveText('1k')
  await page.getByRole('button', { name: 'Editar frecuencia' }).click()
  await page.getByLabel('Frecuencia en hercios').fill('7075000')
  await page.getByLabel('Frecuencia en hercios').press('Enter')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.075.000')
  await zoom.click()
  await expect(zoom).toHaveText('100k')
  await zoom.click()
  await zoom.click()
  await expect(zoom).toHaveText('6k')
  await zoom.click()
  await expect(zoom).toHaveText('BAND')

  const sintonia = page.getByTestId('spectrum-tune')
  await expect(sliceLine).toHaveAttribute('data-selected', 'false')
  await sintonia.focus()
  await expect(sliceLine).toHaveAttribute('data-selected', 'true')
  await expect(sintonia).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.076.000')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('ArrowLeft')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.074.000')
  await page.keyboard.press('ArrowUp')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.075.000')
  await page.keyboard.press('Escape')
  await expect(sliceLine).toHaveAttribute('data-selected', 'false')

  // La sintonía respeta el paso: el clic cae en la rejilla de 1k y, fuera de ella, un paso lleva a la rejilla.
  const caja1k = await sintonia.boundingBox()
  expect(caja1k).not.toBeNull()
  await page.mouse.click(caja1k!.x + caja1k!.width * 0.37, caja1k!.y + 30)
  await expect(sliceLine).toHaveAttribute('data-selected', 'true')
  await expect.poll(async () => Number((await page.getByTestId('vfo-frequency').textContent())!.replaceAll('.', '')) % 1_000).toBe(0)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Editar frecuencia' }).click()
  await page.getByLabel('Frecuencia en hercios').fill('7074350')
  await page.getByLabel('Frecuencia en hercios').press('Enter')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.074.350')
  await sintonia.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.075.000')
  // Sin usarlo unos segundos, el dial se desmarca solo.
  await expect(sliceLine).toHaveAttribute('data-selected', 'false', { timeout: 6_000 })

  await expect(page.getByTestId('s-meter')).toBeVisible()
  const volume = page.getByTestId('volume')
  await expect(volume).toBeEnabled()
  await volume.fill('66')
  await expect(page.getByTestId('volume-value')).toHaveText('66')
  const agc = page.getByTestId('agc')
  await expect(agc).toBeEnabled()
  await agc.selectOption('2')
  await expect(agc).toHaveValue('2')
  await page.getByTestId('nr').click()
  await expect(page.getByTestId('nr')).toHaveText('NR 1')
  await page.getByTestId('nr').click()
  await expect(page.getByTestId('nr')).toHaveText('NR 2')

  await page.getByRole('button', { name: 'Editar frecuencia' }).click()
  await expect(page.getByTestId('freq-editor')).toBeVisible()
  await page.getByTestId('freq-digit-1').click()
  await page.keyboard.press('ArrowUp')
  await expect(page.getByTestId('freq-editor-value')).toHaveText('8.075.000')
  await expect(page.getByTestId('header-frequency')).toContainText('8.075.000')
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('freq-editor')).toHaveCount(0)
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.075.000')

  await page.getByRole('button', { name: 'Editar frecuencia' }).click()
  await page.getByTestId('freq-digit-0').click()
  for (let i = 0; i < 6; i++) {
    await page.keyboard.press('ArrowUp')
  }
  await expect(page.getByTestId('freq-editor-value')).toHaveText('57.075.000')
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.075.000')

  await page.getByRole('button', { name: 'Editar frecuencia' }).click()
  const hercios = page.getByLabel('Frecuencia en hercios')
  await expect(hercios).toBeVisible()
  await hercios.fill('70000000')
  await expect(page.getByTestId('freq-hz-error')).toBeVisible()
  await hercios.press('Enter')
  await expect(hercios).toBeVisible()
  await hercios.press('Escape')
  await expect(page.getByTestId('freq-editor')).toHaveCount(0)
  await expect(page.getByTestId('vfo-frequency')).toHaveText('7.075.000')

  await page.getByRole('button', { name: 'Conectar audio' }).click()
  await expect(page.getByRole('button', { name: 'Desconectar audio' })).toBeVisible()
  await expect(page.getByTestId('audio-scope')).toBeVisible()
  const subir = page.getByRole('button', { name: 'Subir frecuencia' })
  await subir.scrollIntoViewIfNeeded()
  const caja = await subir.boundingBox()
  expect(caja).not.toBeNull()
  const centro = { x: caja!.x + caja!.width / 2, y: caja!.y + caja!.height / 2 }
  await page.mouse.move(centro.x, centro.y)
  await page.mouse.down()
  await page.waitForTimeout(800)
  await page.mouse.up()

  const leerHz = async () => Number((await page.getByTestId('vfo-frequency').textContent())!.replaceAll('.', ''))
  await expect(page.getByRole('button', { name: 'Desconectar audio' })).toBeVisible()
  const trasSostener = await leerHz()
  expect(trasSostener).toBeGreaterThan(7_075_000)
  await page.waitForTimeout(400)
  expect(await leerHz()).toBe(trasSostener)

  // El scan para al aparecer señal en el pasabanda (simulador con señales en su RF real).
  await page.getByRole('radio', { name: 'USB' }).click()
  const irA = async (hz: string, texto: string) => {
    await page.getByRole('button', { name: 'Editar frecuencia' }).click()
    await page.getByLabel('Frecuencia en hercios').fill(hz)
    await page.getByLabel('Frecuencia en hercios').press('Enter')
    await expect(page.getByTestId('vfo-frequency')).toHaveText(texto)
  }
  await expect(page.getByTestId('tuning-step')).toHaveText('1k')

  await irA('7100000', '7.100.000')
  const scanUp = page.getByRole('button', { name: 'Scan hacia arriba' })
  await scanUp.scrollIntoViewIfNeeded()
  await scanUp.click()
  await expect(scanUp).toHaveAttribute('aria-pressed', 'true')
  await page.waitForTimeout(1000)
  expect(await leerHz()).toBeGreaterThan(7_100_000)
  await expect(scanUp).toHaveAttribute('aria-pressed', 'true')
  await scanUp.click()
  await expect(scanUp).toHaveAttribute('aria-pressed', 'false')
  await page.waitForTimeout(500)
  const trasParar = await leerHz()
  await page.waitForTimeout(500)
  expect(await leerHz()).toBe(trasParar)

  await irA('7080000', '7.080.000')
  const scanDown = page.getByRole('button', { name: 'Scan hacia abajo' })
  await scanDown.click()
  await expect(scanDown).toHaveAttribute('aria-pressed', 'false', { timeout: 5_000 })
  const parada = await leerHz()
  expect(parada).toBeGreaterThanOrEqual(7_073_000)
  expect(parada).toBeLessThanOrEqual(7_077_000)
  await page.waitForTimeout(700)
  expect(await leerHz()).toBe(parada)

  expect(errors).toEqual([])

  const a11y = await new AxeBuilder({ page }).analyze()
  expect(a11y.violations).toEqual([])
})
